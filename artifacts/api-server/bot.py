def запустить_ивент(chat_id, принудительно=False):
    """Запускает случайный ивент. принудительно=True игнорирует дневной лимит."""
    if not принудительно and _ивент_уже_был_сегодня(chat_id):
        return False
    перемешанные = СПИСОК_ИВЕНТОВ.copy()
    random.shuffle(перемешанные)
    for название, функция in перемешанные:
        try:
            if функция(chat_id):
                _отметить_ивент(chat_id, название)
                return True
        except Exception as e:
            log.error(f"Ивент '{название}' в чате {chat_id}: {e}")
    return False

def _ивент_планировщик():
    """Фоновый поток: каждые 30 мин проверяет — не пора ли запустить ивент."""
    while True:
        try:
            сегодня = str(date.today())
            час = time.localtime().tm_hour
            rows = _выполнить("SELECT chat_id FROM chats", fetch="all") or []
            for row in rows:
                cid = row["chat_id"]
                seed = abs(hash(cid + сегодня)) % 10
                нужный_час = 12 + seed  # от 12 до 21
                if час >= нужный_час and not _ивент_уже_был_сегодня(cid):
                    try:
                        запустить_ивент(int(cid))
                    except Exception as e:
                        log.error(f"Ивент-планировщик чат {cid}: {e}")
        except Exception as e:
            log.error(f"Ивент-планировщик упал: {e}")
        time.sleep(1800)

_ивент_поток = threading.Thread(target=_ивент_планировщик, daemon=True, name="event-scheduler")
_ивент_поток.start()

