def дневной_бонус(chat_id, user_id, имя):
    """Проверяет и выдаёт дневной бонус. Возвращает текст сообщения или None."""
    сегодня = str(date.today())
    статы = загрузить_статы()
    игрок = получить_игрока(статы, user_id, имя)

    последний = игрок.get("последний_бонус")
    стрик = игрок.get("стрик_бонуса", 0)

    if последний == сегодня:
        return None  # уже получил сегодня

    # Вычисляем стрик
    вчера = str(date.fromordinal(date.today().toordinal() - 1))
    if последний == вчера:
        стрик += 1
    else:
        стрик = 1

    # Базовая награда: 50–300 + стриковый бонус
    база = random.randint(50, 300)
    бонус_стрика = min(стрик - 1, 6) * 50  # +50 за каждый день стрика, макс +300
    итого = база + бонус_стрика

    игрок["последний_бонус"] = сегодня
    игрок["стрик_бонуса"] = стрик
    сохранить_статы(статы)

    начислить_мэлкоины(user_id, имя, итого, chat_id)

    # Ачивки
    if стрик >= 7 and "стрикер" not in игрок.get("ачивки", []):
        дать_ачивку(chat_id, user_id, имя, "стрикер")
    if итого >= 500 and "везунчик" not in игрок.get("ачивки", []):
        дать_ачивку(chat_id, user_id, имя, "везунчик")

    стрик_текст = f"🔥 Стрик: {стрик} день" if стрик == 1 else (
                  f"🔥 Стрик: {стрик} дня" if 2 <= стрик <= 4 else f"🔥 Стрик: {стрик} дней")
    бонус_текст = f" (+{бонус_стрика} за стрик)" if бонус_стрика > 0 else ""

    return (
        f"🎁 *Ежедневный бонус!*\n\n"
        f"💰 +{итого} мэлкоинов{бонус_текст}\n"
        f"{стрик_текст}\n\n"
        f"{'🔥 Возвращайся завтра и получи ещё больше!' if стрик < 7 else '🏆 7 дней подряд! Ты настоящий стрикер!'}"
    )

