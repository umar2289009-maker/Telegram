    # Проверяем ключевые слова
    for ключ, ответы in НЕЙРО_КЛЮЧИ.items():
        if ключ in тч:
            ответ = random.choice(ответы)
            # Иногда добавляем имя
            if random.random() < 0.3 and имя:
                ответ = f"{имя}, {ответ}"
            return ответ
    # Случайный ответ
    ответ = random.choice(НЕЙРО_СЛУЧАЙНЫЕ)
    if random.random() < 0.2 and имя:
        ответ = f"{имя} {ответ}"
    return ответ

