def загрузить_статы() -> dict:
    """Возвращает кэш игроков (без запроса к БД — мгновенно)."""
    if not _КЭШ_ЗАГРУЖЕН:
        _прогреть_кэш()
    return _КЭШСТАТОВ

def сохранить_статы(статы: dict):
    """Обновляет кэш и ставит изменения в фоновую очередь — мгновенно."""
    были_изменения = False
    for user_id, data in статы.items():
        текущий_json = json.dumps(data, ensure_ascii=False, sort_keys=True)
        if текущий_json != _ДБ_СНИМОК.get(user_id):
            _ДБ_СНИМОК[user_id] = текущий_json
            _КЭШСТАТОВ[user_id] = data
            _записать(
                "INSERT INTO players (user_id, data) VALUES (%s, %s) "
                "ON CONFLICT (user_id) DO UPDATE SET data = EXCLUDED.data",
                (user_id, текущий_json)
            )
            были_изменения = True
    if были_изменения:
        _сохранить_бэкап()  # мгновенно пишем в файл при каждом изменении

def получить_игрока(статы, user_id, имя=None):
    ключ = str(user_id)
    если_новый = ключ not in статы
    if если_новый:
        статы[ключ] = {"имя": имя or "незнакомец", "игр": 0, "выжил": 0, "рекорд": 0, "ачивки": [], "пасхалки": []}
    игрок = статы[ключ]
    if "ачивки" not in игрок:
        игрок["ачивки"] = []
    if "пасхалки" not in игрок:
        игрок["пасхалки"] = []
    if "мэлкоины" not in игрок:
        игрок["мэлкоины"] = 0
    if "купленные_титулы" not in игрок:
        игрок["купленные_титулы"] = []
    if "активный_титул" not in игрок:
        игрок["активный_титул"] = None
    if "купленные_справки" not in игрок:
        игрок["купленные_справки"] = []
    # Kolik получает всё при создании аккаунта
    if если_новый and имя and имя.lower() == "kolik":
        _сид_kolik(игрок)
    return игрок

